export function buildAuctionQueue(
  players: AuctionPlayer[],
  orderMode: 'marquee_first' | 'role_wise' | 'random' | 'admin_selected',
  customOrderIds: string[] = [],
  seed = 42,
): string[] {
  const pool = [...players];

  if (orderMode === 'admin_selected' && customOrderIds.length > 0) {
    const validCustom = customOrderIds.filter((id) => PLAYER_MAP[id]);
    const customSet = new Set(validCustom);
    const remaining = pool.map((p) => p.id).filter((id) => !customSet.has(id));
    return [...validCustom, ...remaining];
  }

  if (orderMode === 'role_wise') {
    const roleRank: Record<PlayerRole, number> = {
      BAT: 1,
      WK: 2,
      AR: 3,
      BOWL: 4,
    };
    return pool
      .sort((a, b) => {
        if (roleRank[a.role] !== roleRank[b.role]) {
          return roleRank[a.role] - roleRank[b.role];
        }
        return b.ratings.overall - a.ratings.overall;
      })
      .map((p) => p.id);
  }

  if (orderMode === 'random') {
    let s = seed;
    const nextRand = () => {
      s = (s * 1664525 + 1013904223) % 4294967296;
      return s / 4294967296;
    };
    for (let i = pool.length - 1; i > 0; i--) {
      const j = Math.floor(nextRand() * (i + 1));
      [pool[i], pool[j]] = [pool[j], pool[i]];
    }
    return pool.map((p) => p.id);
  }

  // Default: marquee_first -> Marquee sorted by overall, then Batters, WK, AR, Pace, Spin
  const setOrder = [
    'Marquee',
    'Top-Order Batters',
    'Wicketkeepers',
    'All-Rounders',
    'Fast Bowlers',
    'Spin Bowlers',
    'Middle-Order Batters',
    'Uncapped & Value Batters',
    'Uncapped & Value All-Rounders',
    'Uncapped & Value Pacers',
    'Uncapped & Value Spinners',
  ];
  return pool
    .sort((a, b) => {
      if (a.marquee !== b.marquee) return a.marquee ? -1 : 1;
      const setDiff = setOrder.indexOf(a.setCategory) - setOrder.indexOf(b.setCategory);
      if (setDiff !== 0) return setDiff;
      return b.ratings.overall - a.ratings.overall;
    })
    .map((p) => p.id);
}
